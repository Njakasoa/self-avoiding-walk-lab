"""Benchmark and cross-check the Python and C++ exact enumerators.

Examples::

    PYTHONPATH=. .venv/bin/python benchmarks/enumeration.py --max-n 14
    PYTHONPATH=. .venv/bin/python benchmarks/enumeration.py 20

The C++ executable is compiled in a temporary directory.  The JSON emitted on
stdout contains measurements and counts generated by the two implementations;
no expected count sequence is embedded in this script.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import tempfile
import time
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CPP_SOURCE = ROOT / "src" / "optimized_enumerator.cpp"


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "max_n_positional",
        nargs="?",
        type=int,
        help="largest length (default: 14; useful optional run: 18 or 20)",
    )
    parser.add_argument(
        "--max-n",
        dest="max_n_option",
        type=int,
        help="largest length (equivalent to the positional argument)",
    )
    parser.add_argument(
        "--compiler",
        default="g++",
        help="C++20 compiler executable (default: g++)",
    )
    args = parser.parse_args()
    if args.max_n_positional is not None and args.max_n_option is not None:
        parser.error("specify max_n either positionally or with --max-n, not both")
    args.max_n = (
        args.max_n_option
        if args.max_n_option is not None
        else args.max_n_positional
        if args.max_n_positional is not None
        else 14
    )
    if args.max_n < 0:
        parser.error("max_n must be nonnegative")
    return args


def _compile(binary: Path, compiler: str) -> tuple[list[str], float]:
    compiler_path = shutil.which(compiler)
    if compiler_path is None:
        raise RuntimeError(f"C++ compiler not found: {compiler}")
    command = [
        compiler_path,
        "-std=c++20",
        "-O3",
        "-DNDEBUG",
        str(CPP_SOURCE),
        "-o",
        str(binary),
    ]
    started = time.perf_counter()
    subprocess.run(command, cwd=ROOT, check=True)
    return command, time.perf_counter() - started


def _run_cpp(binary: Path, max_n: int) -> tuple[list[int], float]:
    started = time.perf_counter()
    completed = subprocess.run(
        [str(binary), "--json", str(max_n)],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    elapsed = time.perf_counter() - started
    # Parse through JSON and keep counts as JSON integers in the report.
    values = json.loads(completed.stdout)
    if not isinstance(values, list) or any(
        isinstance(value, bool) or not isinstance(value, int) for value in values
    ):
        raise RuntimeError("optimized enumerator did not emit an integer JSON list")
    return values, elapsed


def main() -> None:
    args = _parse_args()
    with tempfile.TemporaryDirectory(prefix="saw-enumeration-") as temporary:
        binary = Path(temporary) / "optimized_enumerator"
        compile_command, compile_seconds = _compile(binary, args.compiler)

        started = time.perf_counter()
        reference_values = _reference_counts(args.max_n)
        reference_seconds = time.perf_counter() - started

        optimized_values, optimized_seconds = _run_cpp(binary, args.max_n)
        if optimized_values != reference_values:
            raise RuntimeError(
                "reference and optimized enumerators disagree at "
                f"max_n={args.max_n}"
            )

    report = {
        "classification": "EXACT INTEGER",
        "max_n": args.max_n,
        "reference": {
            "seconds": reference_seconds,
            "counts": reference_values,
        },
        "optimized": {
            "compile_seconds": compile_seconds,
            "seconds": optimized_seconds,
            "counts": optimized_values,
        },
        "commands": {
            "compile": compile_command,
            "optimized": ["optimized_enumerator", "--json", str(args.max_n)],
        },
    }
    print(json.dumps(report, indent=2))


def _reference_counts(max_n: int) -> list[int]:
    # Keep the import local so --help does not require the package import path
    # to have been configured, while normal execution remains straightforward.
    import sys

    sys.path.insert(0, str(ROOT))
    from src.reference_enumerator import counts

    return counts(max_n)


if __name__ == "__main__":
    main()
